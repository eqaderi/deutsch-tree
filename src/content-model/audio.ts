/**
 * Audio in the content model: the voices German is spoken in, and what a
 * piece of German that the learner can hear carries in the compiled bundle.
 *
 * The voices were chosen on ticket #5: Piper's Thorsten (medium) reads
 * everything, and Kerstin (medium) is the second voice of a dialogue. A
 * third voice, for the radio discussion of three people in Hören, Teil 4,
 * was added on ticket #27: one speaker of Piper's MLS (medium) model. Since
 * ticket #41 the learner chooses Thorsten or Kerstin for everything that one
 * person says (`CHOOSABLE_VOICES`); a dialogue keeps its speakers' voices.
 */
import { z } from 'zod'

export const VOICE_IDS = ['thorsten', 'kerstin', 'mls-5424'] as const
/** A voice by name. A content field that names who speaks takes one of these (`voiceSchema`). */
export type VoiceId = (typeof VOICE_IDS)[number]

/** For a content field that says who speaks a line: `voice: kerstin`. */
export const voiceSchema = z.enum(VOICE_IDS)

/**
 * The voices a learner may choose for everything one person says (examples,
 * words, phrases, mistakes): the main voice first, then the second. The
 * choice is part of the learner's progress (`voice`). Every such piece of
 * German has a file in each of them.
 */
export const CHOOSABLE_VOICES = ['thorsten', 'kerstin'] as const
export type ChoosableVoice = (typeof CHOOSABLE_VOICES)[number]

/** The main voice: what a learner hears who has chosen nothing. A dialogue names the voice of each line. */
export const DEFAULT_VOICE: ChoosableVoice = 'thorsten'

export interface Voice {
  /** The Piper voice model, as the files `<model>.onnx` and `<model>.onnx.json` are named. */
  model: string
  /** Of a model with many speakers: the number Piper gives the one that speaks (`piper --speaker`). */
  speaker?: number
  /** Whether the site must credit the voice; the credit line itself is an interface string (`voiceCredit`). */
  needsCredit: boolean
}

/**
 * The voices. Thorsten and Kerstin are CC0. Kerstin is trained on top of a
 * model made from Hi-Fi TTS (CC BY 4.0, NVIDIA; reader Cori Samuel), so the
 * site credits it. The MLS model is trained on Multilingual LibriSpeech (CC
 * BY 4.0, Facebook AI; read from LibriVox audiobooks), so the site credits it
 * too. `mls-5424` is its speaker 5424 of that data set, Piper's speaker 12:
 * a voice clearly higher than Kerstin's, so three speakers of one text are
 * told apart by ear. Changing a voice's model keeps its audio keys:
 * regenerate with `--force`.
 */
export const VOICES: Readonly<Record<VoiceId, Voice>> = {
  thorsten: { model: 'de_DE-thorsten-medium', needsCredit: false },
  kerstin: { model: 'de_DE-kerstin-medium', needsCredit: true },
  'mls-5424': { model: 'de_DE-mls-medium', speaker: 12, needsCredit: true },
}

/**
 * German that the learner can hear: what the voice says, which voice says it,
 * and the key of the file that holds it. The pipeline attaches one as `audio`
 * to every piece of German that has a play button; whatever carries one is
 * generated by `pnpm audio:generate` and checked for its file.
 */
export interface Spoken {
  /** A hash of the voice and the spoken text, so the same words in the same voice are one file. */
  key: string
  voice: VoiceId
  /** The text as the voice says it: numbers written as words. It may differ from the text shown. */
  text: string
  /**
   * Of German that one person says (not a line of a dialogue): the key of
   * the same text in each voice the learner may choose. `key` and `voice`
   * are then those of the main voice. A play button plays the learner's
   * choice (`keyFor`).
   */
  byVoice?: Readonly<Record<ChoosableVoice, string>>
}

/** The key a play button plays: of the learner's chosen voice when the learner may choose, else of the speaker's. */
export function keyFor(audio: Spoken, chosen: ChoosableVoice): string {
  return audio.byVoice?.[chosen] ?? audio.key
}

/** The folder of the audio files, inside the content folder and inside the site's `content/` folder. */
export const AUDIO_FOLDER = 'audio'

/** Where the audio of a key lives, relative to the content folder: "audio/<key>.mp3". */
export function audioFile(key: string): string {
  return `${AUDIO_FOLDER}/${key}.mp3`
}
