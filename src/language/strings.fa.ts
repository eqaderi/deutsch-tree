/**
 * Latin text inside a Persian string (German, a name, a command, a version),
 * kept apart from the Persian around it by the Unicode marks U+2066 … U+2069,
 * since a string cannot hold a <span>. It then reads left to right.
 */
function german(text: string): string {
  return `⁦${text}⁩`
}
